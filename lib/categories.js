export function matchCategory(keyword) {
  const kw = String(keyword || '').trim()
  if (!kw) return '综合全部'
  if (VALID_CATEGORIES.includes(kw)) return kw
  for (const [category, words] of Object.entries(CATEGORY_KEYWORDS)) {
    for (const w of words) {
      if (kw.includes(w) || w.includes(kw)) return category
    }
  }
  return '综合全部'
}
